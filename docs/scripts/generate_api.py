"""Generate public API references separately from authored guides."""

import argparse
import importlib
import inspect
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
OUTPUT = ROOT / "docs/API/generated"
NOTICE = "<!-- Generated by docs/scripts/generate_api.py; do not edit. -->\n"


def pages():
    """Follow public source modules and their explicit export lists."""
    output = {}
    index = [
        NOTICE,
        "# Public API",
        "",
        "Reference pages follow the package's public exports.",
        "",
    ]
    for source in sorted((ROOT / "src/zodiax").rglob("*.py")):
        relative = source.relative_to(ROOT / "src").with_suffix("")
        if any(part.startswith("_") for part in relative.parts):
            continue
        module_name = ".".join(relative.parts)
        module = importlib.import_module(module_name)
        names = getattr(module, "__all__", ())
        if not names:
            continue
        filename = "_".join(relative.parts[1:]) + ".md"
        index.append(f"- [{module_name}]({filename})")
        lines = [NOTICE, f"# {module_name}", ""]
        classes = [
            getattr(module, name)
            for name in names
            if inspect.isclass(getattr(module, name))
        ]
        if classes:
            lines.extend(["```mermaid", "classDiagram"])
            for cls in classes:
                for base in cls.__bases__:
                    if base is not object:
                        lines.append(f"    {base.__name__} <|-- {cls.__name__}")
            lines.extend(["```", ""])
        for name in names:
            obj = getattr(module, name)
            lines.extend([f"::: {module_name}.{name}"])
            if inspect.isclass(obj):
                lines.extend(
                    [
                        "    options:",
                        "      merge_init_into_class: true",
                        "      inherited_members: [__init__]",
                    ]
                )
            lines.append("")
        output[filename] = "\n".join(lines).rstrip() + "\n"
    output["index.md"] = "\n".join(index) + "\n"
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = pages()
    existing = {path.name: path.read_text() for path in OUTPUT.glob("*.md")}
    if args.check:
        changed = sorted(
            name
            for name in expected.keys() | existing.keys()
            if expected.get(name) != existing.get(name)
        )
        if changed:
            raise SystemExit("Regenerate API pages: " + ", ".join(changed))
        print("Generated API pages are current.")
        return
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for name in existing.keys() - expected.keys():
        (OUTPUT / name).unlink()
    for name, content in expected.items():
        (OUTPUT / name).write_text(content)
    print(f"Generated {len(expected)} API pages.")


if __name__ == "__main__":
    main()
